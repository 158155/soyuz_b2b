def build_user_prompt(product: dict) -> str:
    """Формирует пользовательский промпт из данных товара."""
    import json

    return (
        "Входные данные о товаре (JSON):\n"
        + json.dumps(product, ensure_ascii=False, indent=2)
        + "\n\nСформируй черновик карточки по правилам. Верни только JSON."
    )
